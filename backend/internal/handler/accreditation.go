type AccreditationHandler struct {
	db *pgxpool.Pool
}

func NewAccreditationHandler(db *pgxpool.Pool) *AccreditationHandler {
	return &AccreditationHandler{db: db}
}

// ══════════════════════════════════════════════════
// Evidence Registry
// ══════════════════════════════════════════════════

type evidenceRow struct {
	ID             string  `json:"id"`
	Body           string  `json:"accreditation_body"`
	StandardCode   string  `json:"standard_code"`
	StandardNameAr *string `json:"standard_name_ar"`
	EvidenceType   string  `json:"evidence_type"`
	Description    *string `json:"evidence_description"`
	URL            *string `json:"evidence_url"`
	AutoGenerated  bool    `json:"auto_generated"`
	CycleYear      *int    `json:"cycle_year"`
	Status         string  `json:"status"`
	CreatedAt      string  `json:"created_at"`
}

func (h *AccreditationHandler) ListEvidence(w http.ResponseWriter, r *http.Request) {
	ctx, cancel := context.WithTimeout(r.Context(), 5*time.Second)
	defer cancel()

	body := r.URL.Query().Get("body")
	query := `
		SELECT id, accreditation_body, standard_code, standard_name_ar,
		       evidence_type, evidence_description, evidence_url,
		       auto_generated, cycle_year, status, created_at
		FROM accreditation_evidence
	`
	args := []any{}
	if body != "" {
		query += ` WHERE accreditation_body = $1::accreditation_body`
		args = append(args, body)
	}
	query += ` ORDER BY standard_code, created_at DESC LIMIT 100`

	rows, err := h.db.Query(ctx, query, args...)
	if err != nil {
		model.RespondError(w, http.StatusInternalServerError, "Failed to fetch evidence")
		return
	}
	defer rows.Close()

	items := []evidenceRow{}
	for rows.Next() {
		var e evidenceRow
		var createdAt time.Time
		rows.Scan(&e.ID, &e.Body, &e.StandardCode, &e.StandardNameAr,
			&e.EvidenceType, &e.Description, &e.URL,
			&e.AutoGenerated, &e.CycleYear, &e.Status, &createdAt)
		e.CreatedAt = createdAt.Format(time.RFC3339)
		items = append(items, e)
	}
	model.RespondJSON(w, http.StatusOK, items)
}

func (h *AccreditationHandler) CreateEvidence(w http.ResponseWriter, r *http.Request) {
	var req struct {
		Body           string `json:"accreditation_body"`
		StandardCode   string `json:"standard_code"`
		StandardNameAr string `json:"standard_name_ar"`
		EvidenceType   string `json:"evidence_type"`
		Description    string `json:"evidence_description"`
		URL            string `json:"evidence_url"`
		CollegeID      string `json:"college_id"`
		CycleYear      int    `json:"cycle_year"`
	}
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		model.RespondError(w, http.StatusBadRequest, "Invalid request body")
		return
	}

	ctx, cancel := context.WithTimeout(r.Context(), 5*time.Second)
	defer cancel()

	id := uuid.New().String()
	_, err := h.db.Exec(ctx, `
		INSERT INTO accreditation_evidence
			(id, institution_id, accreditation_body, standard_code, standard_name_ar,
			 evidence_type, evidence_description, evidence_url, college_id, cycle_year, status)
		VALUES ($1, '11111111-1111-1111-1111-111111111111', $2::accreditation_body, $3, $4,
		        $5::evidence_type, $6, $7, NULLIF($8, '')::uuid, $9, 'submitted')
	`, id, req.Body, req.StandardCode, req.StandardNameAr,
		req.EvidenceType, req.Description, req.URL, req.CollegeID, req.CycleYear)
	if err != nil {
		model.RespondError(w, http.StatusBadRequest, "Failed to create evidence: "+err.Error())
		return
	}
	model.RespondJSON(w, http.StatusCreated, map[string]string{"id": id})
}

// ══════════════════════════════════════════════════
// Accreditation Recommendations Tracker
// ══════════════════════════════════════════════════

func (h *AccreditationHandler) ListRecommendations(w http.ResponseWriter, r *http.Request) {
	ctx, cancel := context.WithTimeout(r.Context(), 5*time.Second)
	defer cancel()

	rows, err := h.db.Query(ctx, `
		SELECT id, accreditation_body, recommendation_type, recommendation_text,
		       improvement_plan, deadline, completion_percentage, status
		FROM accreditation_recommendations
		ORDER BY CASE status WHEN 'overdue' THEN 0 WHEN 'open' THEN 1 WHEN 'in_progress' THEN 2 ELSE 3 END,
		         deadline ASC NULLS LAST
		LIMIT 50
	`)
	if err != nil {
		model.RespondError(w, http.StatusInternalServerError, "Failed to fetch")
		return
	}
	defer rows.Close()

	type recRow struct {
		ID            string  `json:"id"`
		Body          string  `json:"accreditation_body"`
		Type          string  `json:"recommendation_type"`
		Text          string  `json:"recommendation_text"`
		Plan          *string `json:"improvement_plan"`
		Deadline      *string `json:"deadline"`
		CompletionPct int     `json:"completion_percentage"`
		Status        string  `json:"status"`
	}
	items := []recRow{}
	for rows.Next() {
		var i recRow
		var deadline *time.Time
		rows.Scan(&i.ID, &i.Body, &i.Type, &i.Text, &i.Plan, &deadline, &i.CompletionPct, &i.Status)
		if deadline != nil {
			s := deadline.Format("2006-01-02")
			i.Deadline = &s
		}
		items = append(items, i)
	}
	model.RespondJSON(w, http.StatusOK, items)
}

func (h *AccreditationHandler) UpdateRecommendation(w http.ResponseWriter, r *http.Request) {
	id := chi.URLParam(r, "id")
	var req struct {
		CompletionPercentage int    `json:"completion_percentage"`
		Status               string `json:"status"`
		EvidenceOfAction     string `json:"evidence_of_action"`
	}
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		model.RespondError(w, http.StatusBadRequest, "Invalid request body")
		return
	}

	ctx, cancel := context.WithTimeout(r.Context(), 5*time.Second)
	defer cancel()

	_, err := h.db.Exec(ctx, `
		UPDATE accreditation_recommendations SET
			completion_percentage = $2,
			status = $3::recommendation_status,
			evidence_of_action = COALESCE(NULLIF($4, ''), evidence_of_action),
			updated_at = NOW()
		WHERE id = $1
	`, id, req.CompletionPercentage, req.Status, req.EvidenceOfAction)
	if err != nil {
		model.RespondError(w, http.StatusBadRequest, "Update failed")
		return
	}
	model.RespondJSON(w, http.StatusOK, map[string]string{"updated": id})
}

// ══════════════════════════════════════════════════
// Strategic KPIs
// ══════════════════════════════════════════════════

func (h *AccreditationHandler) ListKPIs(w http.ResponseWriter, r *http.Request) {
	ctx, cancel := context.WithTimeout(r.Context(), 5*time.Second)
	defer cancel()

	year, _ := strconv.Atoi(r.URL.Query().Get("year"))
	if year == 0 {
		year = time.Now().Year()
	}

	rows, err := h.db.Query(ctx, `
		SELECT id, kpi_name_ar, kpi_name_en, category, target_value,
		       minimum_value, excellence_value, actual_value, unit,
		       measurement_period, data_source
		FROM strategic_kpis
		WHERE year = $1
		ORDER BY category, kpi_name_ar
	`, year)
	if err != nil {
		model.RespondError(w, http.StatusInternalServerError, "Failed to fetch KPIs")
		return
	}
	defer rows.Close()

	type kpiRow struct {
		ID              string   `json:"id"`
		NameAr          string   `json:"kpi_name_ar"`
		NameEn          *string  `json:"kpi_name_en"`
		Category        string   `json:"category"`
		TargetValue     *float64 `json:"target_value"`
		MinimumValue    *float64 `json:"minimum_value"`
		ExcellenceValue *float64 `json:"excellence_value"`
		ActualValue     *float64 `json:"actual_value"`
		Unit            *string  `json:"unit"`
		Period          string   `json:"measurement_period"`
		DataSource      string   `json:"data_source"`
	}
	items := []kpiRow{}
	for rows.Next() {
		var k kpiRow
		rows.Scan(&k.ID, &k.NameAr, &k.NameEn, &k.Category, &k.TargetValue,
			&k.MinimumValue, &k.ExcellenceValue, &k.ActualValue, &k.Unit, &k.Period, &k.DataSource)
		items = append(items, k)
	}
	model.RespondJSON(w, http.StatusOK, items)
}

// ══════════════════════════════════════════════════
// Accreditation Dashboard Summary
// ══════════════════════════════════════════════════

type accreditationSummary struct {
	TotalEvidence    int     `json:"total_evidence"`
	AcceptedEvidence int     `json:"accepted_evidence"`
	CompletionPct    float64 `json:"completion_pct"`
	OpenRecs         int     `json:"open_recommendations"`
	OverdueRecs      int     `json:"overdue_recommendations"`
	TotalKPIs        int     `json:"total_kpis"`
	KPIsOnTarget     int     `json:"kpis_on_target"`
}

func (h *AccreditationHandler) Dashboard(w http.ResponseWriter, r *http.Request) {
	ctx, cancel := context.WithTimeout(r.Context(), 10*time.Second)
	defer cancel()

	var s accreditationSummary
	h.db.QueryRow(ctx, `SELECT COUNT(*) FROM accreditation_evidence`).Scan(&s.TotalEvidence)
	h.db.QueryRow(ctx, `SELECT COUNT(*) FROM accreditation_evidence WHERE status = 'accepted'`).Scan(&s.AcceptedEvidence)
	if s.TotalEvidence > 0 {
		s.CompletionPct = float64(s.AcceptedEvidence) / float64(s.TotalEvidence) * 100
	}
	h.db.QueryRow(ctx, `SELECT COUNT(*) FROM accreditation_recommendations WHERE status IN ('open', 'in_progress')`).Scan(&s.OpenRecs)
	h.db.QueryRow(ctx, `SELECT COUNT(*) FROM accreditation_recommendations WHERE status = 'overdue'`).Scan(&s.OverdueRecs)
	h.db.QueryRow(ctx, `SELECT COUNT(*) FROM strategic_kpis WHERE year = EXTRACT(YEAR FROM CURRENT_DATE)`).Scan(&s.TotalKPIs)
	h.db.QueryRow(ctx, `SELECT COUNT(*) FROM strategic_kpis WHERE year = EXTRACT(YEAR FROM CURRENT_DATE) AND actual_value >= target_value`).Scan(&s.KPIsOnTarget)

	model.RespondJSON(w, http.StatusOK, s)
}
